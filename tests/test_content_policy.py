import unittest

from artfinder.domain.content_policy import is_ai_generated, matched_ai_indicators


class ContentPolicyTests(unittest.TestCase):
    def test_ai_metadata_is_always_rejected(self):
        self.assertTrue(is_ai_generated({"tags": "portrait ai_generated"}))
        self.assertTrue(is_ai_generated({"tags": "portrait generated by ai"}))
        self.assertTrue(is_ai_generated({"tags": ["portrait", "stable_diffusion"]}))
        self.assertTrue(is_ai_generated({"is_ai": True, "tags": "portrait"}))

    def test_normal_art_tags_are_not_rejected(self):
        post = {"tags": "digital_art painting vex_(league_of_legends)"}
        self.assertFalse(is_ai_generated(post))
        self.assertEqual(matched_ai_indicators(post), set())


if __name__ == "__main__":
    unittest.main()
