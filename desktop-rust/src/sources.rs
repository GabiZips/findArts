    #[ignore = "requer internet e credenciais das fontes privadas"]
    fn live_sources() {
        let mut workers = vec![];
        for s in SOURCES {
            workers.push(std::thread::spawn(move || {
                let page = search(
                    s,
                    if s == "Bluesky" {
                        "landscape art"
                    } else {
                        "landscape"
                    },
                    None,
                )
                .map_err(|e| format!("busca: {e}"))?;
                let p = page
                    .posts
                    .first()
                    .ok_or_else(|| format!("{s}: sem mídia"))?;
                let preview = crate::thumbnail(p, None).map_err(|e| format!("prévia: {e}"))?;
                let original = media(p, false).map_err(|e| format!("original: {e}"))?;
                if crate::library::video_ext(&original).is_none() {
                    crate::library::decode(&original)?;
                }
                Ok::<_, String>((page.posts.len(), preview.size, original.len()))
            }));
        }
        let mut failed = vec![];
        for (s, w) in SOURCES.into_iter().zip(workers) {
            match w.join().unwrap() {
                Ok((count, [width, height], original)) => {
                    println!(
                        "{s}: {count} posts, prévia {width}×{height}, original ({original} bytes)"
                    )
                }
                Err(e) => {
                    println!("{s}: {e}");
                    failed.push(s)
                }
            }
        }
        assert!(failed.is_empty(), "Sem validação completa: {failed:?}");
    }
