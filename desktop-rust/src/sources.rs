pub fn map_tags(s: &str, query: &str) -> R<String> {
    let a = http();
    let mut terms = Vec::new();
    let tokens = query.split_whitespace().take(5).collect::<Vec<_>>();
    if tokens.is_empty() || tokens.len() > 4 {
        return Err("Use de uma a quatro tags para mapear".into());
    }
    for token in tokens {
        let name = token.trim_start_matches('-');
        let neg = token.starts_with('-');
        let resolved = if s == "Pixiv" {
            if neg {
                continue;
            }
            let pages = api(a
                .get("https://danbooru.donmai.us/wiki_pages.json")
                .query("search[title]", name)
                .call())?;
            pages
                .pointer("/0/other_names")
                .and_then(Value::as_array)
                .and_then(|a| a.iter().filter_map(Value::as_str).find(|n| !n.is_ascii()))
                .unwrap_or(name)
                .to_owned()
        } else {
            let base = name.split("_(").next().unwrap_or(name);
            let root = api(a
                .get("https://e621.net/tags/autocomplete.json")
                .query("search[name_matches]", base)
                .call())?;
            let rows = root.as_array().ok_or("Resposta de tags inválida")?;
            let context = name.split_once("_(").map(|(_, c)| c.trim_end_matches(')'));
            let matched = rows
                .iter()
                .filter(|v| {
                    v["name"].as_str().is_some_and(|n| {
                        n == name || (n.starts_with(base) && context.is_none_or(|c| n.contains(c)))
                    })
                })
                .max_by_key(|v| {
                    (
                        v["name"] == name,
                        v["post_count"].as_i64().unwrap_or_default(),
                    )
                })
                .and_then(|v| v["name"].as_str())
                .unwrap_or(name);
            format!("{}{matched}", if neg { "-" } else { "" })
        };
        terms.push(resolved)
    }
    let q = terms.join(" ");
    if q.is_empty() || search(s, &q, None)?.posts.is_empty() {
        Err("Nenhuma correspondência confirmada".into())
    } else {
        Ok(q)
    }
}
