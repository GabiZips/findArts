fn val(v: &Value, p: &str) -> String {
    match v.pointer(p) {
        Some(Value::String(s)) => s.clone(),
        Some(Value::Number(n)) => n.to_string(),
        _ => String::new(),
    }
}
fn first(v: &Value, keys: &[&str]) -> String {
    keys.iter()
        .map(|k| val(v, k))
        .find(|s| !s.is_empty())
        .unwrap_or_default()
}
fn list(v: &Value) -> String {
    match v {
        Value::Array(a) => a
            .iter()
            .filter_map(|x| x.as_str().or_else(|| x["name"].as_str()))
            .collect::<Vec<_>>()
            .join(" "),
        Value::String(s) => s.clone(),
        _ => String::new(),
    }
}
