pub type R<T> = Result<T, String>;
pub fn vault(k: &str) -> R<keyring::Entry> {
    keyring::Entry::new("io.github.gabizips.artfinder.rust", k)
        .map_err(|_| "Cofre indisponível".into())
}
static SESSION: std::sync::LazyLock<std::sync::Mutex<std::collections::HashMap<String, String>>> =
    std::sync::LazyLock::new(Default::default);
pub fn session_set(k: &str, v: &str) {
    if let Ok(mut map) = SESSION.lock() {
        map.insert(k.to_owned(), v.to_owned());
    }
}
pub fn credential(k: &str) -> Option<String> {
    std::env::var(k)
        .ok()
        .or_else(|| vault(k).ok()?.get_password().ok())
        .filter(|v| !v.is_empty())
        .or_else(|| SESSION.lock().ok()?.get(k).cloned())
}
fn need(k: &str) -> R<String> {
    credential(k).ok_or_else(|| format!("Configure {k}"))
}
