"""Mandatory content policies shared by desktop search flows."""

from __future__ import annotations

import re
from collections.abc import Mapping


AI_TAGS = frozenset(
    {
        "ai_generated",
        "ai-generated",
        "ai_art",
        "stable_diffusion",
        "novelai",
        "nai_diffusion",
        "midjourney",
        "dall-e",
        "dall_e",
        "image_generation",
        "automated_art",
        "diffusion_model",
        "generated_by_ai",
        "aigc",
        "aiart",
        "stablediffusion",
        "artificialintelligence",
    }
)
AI_PHRASES = ("ai generated", "generated by ai", "ai-generated")


def matched_ai_indicators(post: Mapping) -> set[str]:
    """Return deterministic source metadata that identifies generated artwork."""
    if post.get("is_ai") in (True, 1, "1"):
        return {"is_ai"}
    raw_tags = post.get("tags") or ""
    if isinstance(raw_tags, (list, tuple, set)):
        raw_tags = " ".join(str(value) for value in raw_tags)
    normalized = str(raw_tags).lower()
    tokens = set(re.findall(r"[a-z0-9_-]+", normalized))
    matches = tokens & AI_TAGS
    matches.update(phrase for phrase in AI_PHRASES if phrase in normalized)
    return matches


def is_ai_generated(post: Mapping) -> bool:
    """AI filtering is a product policy and cannot be disabled by configuration."""
    return bool(matched_ai_indicators(post))
